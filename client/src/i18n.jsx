const SettingsContext = createContext(null);

function readInitial(name, fallback) {
  if (typeof window === 'undefined') return fallback;
  return localStorage.getItem(name) || fallback;
}

export function SettingsProvider({ children }) {
  const [lang, setLangState] = useState(() => readInitial('campuseats_lang', readInitial('qr_dine_lang', 'tr')));
  const [theme, setThemeState] = useState(() => readInitial('campuseats_theme', readInitial('qr_dine_theme', 'light')));

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dataset.theme = theme;
    localStorage.setItem('campuseats_lang', lang);
    localStorage.setItem('campuseats_theme', theme);
    localStorage.removeItem('qr_dine_lang');
    localStorage.removeItem('qr_dine_theme');
  }, [lang, theme]);

  const value = useMemo(() => ({
    lang,
    theme,
    setLang: setLangState,
    setTheme: setThemeState,
    t(key) {
      return dictionaries[lang]?.[key] || dictionaries.en[key] || key;
    }
  }), [lang, theme]);

  return <SettingsContext.Provider value={value}>{children}</SettingsContext.Provider>;
}

export function useSettings() {
  const context = useContext(SettingsContext);
  if (!context) throw new Error('useSettings must be used inside SettingsProvider');
  return context;
}

export function SettingsControls({ compact = false, floating = false }) {
  const { lang, theme, setLang, setTheme, t } = useSettings();
  const className = ['settingsControls', compact ? 'compact' : '', floating ? 'floating' : ''].filter(Boolean).join(' ');
  return (
    <div className={className} aria-label={`${t('language')} / ${t('theme')}`}>
      <div className="segmentedGroup" role="group" aria-label={t('language')}>
        <button type="button" className={lang === 'tr' ? 'active' : ''} onClick={() => setLang('tr')} title="Türkçe">TR</button>
        <button type="button" className={lang === 'en' ? 'active' : ''} onClick={() => setLang('en')} title="English">EN</button>
      </div>
      <div className="segmentedGroup themeGroup" role="group" aria-label={t('theme')}>
        <button type="button" className={theme === 'light' ? 'active' : ''} onClick={() => setTheme('light')} title={t('light')}>☀️</button>
        <button type="button" className={theme === 'dark' ? 'active' : ''} onClick={() => setTheme('dark')} title={t('dark')}>🌙</button>
      </div>
    </div>
  );
}
